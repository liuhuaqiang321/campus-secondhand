-- 8.2 新用户注册后自动写入 profiles（兜底方案）
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_name text;
begin
    v_name := coalesce(
        new.raw_user_meta_data->>'username',
        split_part(new.email, '@', 1),
        'user'
    );
    insert into public.profiles (id, username, nickname, phone, avatar, school)
    values (
        new.id,
        v_name,
        coalesce(new.raw_user_meta_data->>'nickname', v_name),
        nullif(new.raw_user_meta_data->>'phone', ''),
        coalesce(new.raw_user_meta_data->>'avatar', ''),
        nullif(new.raw_user_meta_data->>'school', '')
    );
    return new;
exception
    when others then
        raise warning 'handle_new_user 写入 profiles 失败: %', sqlerrm;
        return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- 8.3 浏览量自增（绕过 RLS，允许任何访客增加浏览数）
