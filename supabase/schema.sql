-- ============================================================
-- 1. 用户资料表 profiles
--    对应原 MySQL 的 user 表
--    user 是 PostgreSQL 保留字，故改名 profiles
--    id 关联 Supabase 自带的认证表 auth.users
-- ============================================================
create table if not exists public.profiles (
    id           uuid        primary key references auth.users(id) on delete cascade,
    username     text        unique not null,
    nickname     text,
    phone        text,
    avatar       text        default '',
    school       text,
    role         smallint    not null default 0,   -- 0-普通用户 1-管理员
    status       smallint    not null default 1,   -- 0-禁用 1-正常
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);
comment on table public.profiles is '用户资料表';

-- ============================================================
-- 2. 物品种类表 category
-- ============================================================
create table if not exists public.category (
    id          bigint generated by default as identity primary key,
    name        text     not null,
    parent_id   bigint   not null default 0,      -- 0 表示一级分类
    sort_order  integer  not null default 0,
    status      smallint not null default 1,
    created_at  timestamptz not null default now()
);

-- ============================================================
-- 3. 物品表 item
--    images 由 MySQL 的逗号分隔字符串改为 PostgreSQL 数组
-- ============================================================
create table if not exists public.item (
    id              bigint generated by default as identity primary key,
    title           text      not null,
    category_id     bigint    not null references public.category(id),
    user_id         uuid      not null references public.profiles(id) on delete cascade,
    price           numeric(10,2) not null,
    original_price  numeric(10,2),
    description     text,
    images          text[]    not null default '{}',
    condition       smallint  not null default 1,  -- 1-全新 2-几乎全新 3-轻微使用 4-明显使用
    status          smallint  not null default 1,  -- 0-已下架 1-在售 2-已售出 3-已预订
    view_count      integer   not null default 0,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);
create index if not exists idx_item_category   on public.item(category_id);
create index if not exists idx_item_user       on public.item(user_id);
create index if not exists idx_item_status     on public.item(status);
create index if not exists idx_item_title      on public.item(title);
create index if not exists idx_item_created    on public.item(created_at desc);

