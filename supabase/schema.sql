end $$;

-- 8.4 下单（原子操作：校验库存状态 + 落单 + 置为已预订）
create or replace function public.create_order(p_item_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_uid   uuid := auth.uid();
    v_item  public.item%rowtype;
    v_oid   bigint;
begin
    if v_uid is null then
        raise exception '请先登录后再下单';
    end if;

    select * into v_item from public.item where id = p_item_id for update;
    if not found then
        raise exception '物品不存在或已删除';
    end if;
    if v_item.status <> 1 then
        raise exception '该物品当前不可购买';
    end if;
    if v_item.user_id = v_uid then
        raise exception '不能购买自己发布的物品';
    end if;

    insert into public.orders (order_no, item_id, buyer_id, seller_id, amount, status)
    values (
        'CS' || to_char(now(), 'YYYYMMDDHH24MISS') || lpad(floor(random()*1000000)::text, 6, '0'),
        p_item_id, v_uid, v_item.user_id, v_item.price, 1
    ) returning id into v_oid;

    update public.item set status = 3 where id = p_item_id;
    return v_oid;
end $$;

-- 8.5 订单状态流转（pay 付款 / ship 发货 / confirm 收货 / cancel 取消）
create or replace function public.update_order_status(p_order_id bigint, p_action text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_uid  uuid := auth.uid();
    v_ord  public.orders%rowtype;
begin
    if v_uid is null then
        raise exception '请先登录';
    end if;

    select * into v_ord from public.orders where id = p_order_id for update;
    if not found then
        raise exception '订单不存在';
    end if;
    if v_ord.buyer_id <> v_uid and v_ord.seller_id <> v_uid then
        raise exception '无权操作该订单';
    end if;

    if p_action = 'pay' then
        if v_ord.buyer_id <> v_uid then raise exception '只有买家可以付款'; end if;
        if v_ord.status <> 1 then raise exception '当前状态不可付款'; end if;
        update public.orders set status = 2, pay_time = now() where id = p_order_id;

    elsif p_action = 'ship' then
        if v_ord.seller_id <> v_uid then raise exception '只有卖家可以发货'; end if;
        if v_ord.status <> 2 then raise exception '买家尚未付款，无法发货'; end if;
        update public.orders set status = 3, ship_time = now() where id = p_order_id;

    elsif p_action = 'confirm' then
        if v_ord.buyer_id <> v_uid then raise exception '只有买家可以确认收货'; end if;
        if v_ord.status <> 3 then raise exception '订单尚未发货'; end if;
        update public.orders set status = 4, complete_time = now() where id = p_order_id;
        update public.item set status = 2 where id = v_ord.item_id;

    elsif p_action = 'cancel' then
        if v_ord.buyer_id <> v_uid then raise exception '只有买家可以取消订单'; end if;
        if v_ord.status in (4, 5) then raise exception '该订单无法取消'; end if;
        update public.orders set status = 5, cancel_time = now() where id = p_order_id;
        update public.item set status = 1 where id = v_ord.item_id and status = 3;

    else
        raise exception '未知操作: %', p_action;
    end if;
end $$;

